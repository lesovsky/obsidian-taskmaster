/**
 * Отображаемое название группы: сохранённое, если оно непустое, иначе дефолтная подпись.
 *
 * Аргументы — простые строки, а не объект группы: модуль остаётся чистым и не зависит
 * ни от модели данных, ни от i18n-стора. Дефолтную подпись добывает вызывающая сторона.
 * Возвращаемое значение — пользовательский ввод как есть: выводить только через
 * {}-интерполяцию, не через {@html}.
 */
export function resolveGroupTitle(storedTitle: string, defaultLabel: string): string {
  return storedTitle.trim() !== '' ? storedTitle : defaultLabel;
}
